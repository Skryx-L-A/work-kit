class Pi(Target):
    name, label = "pi", "pi coding agent"
    binaries = ["pi"]
    protocols = "OpenAI chat, OpenAI Responses, Anthropic, Azure Responses, Gemini"
    mechanism = ("~/.pi/agent/models.json providers.<name> (\"$VAR\" key); default: settings.json "
                 "defaultProvider/defaultModel. With 70-workbench installed, wb-state writes the provider")

    def pdir(self):
        return Path(os.environ.get("PI_CODING_AGENT_DIR") or self.home / ".pi/agent")

    def config_dirs(self):
        return [self.pdir()]

    def route(self, ep):
        return "proxy" if ep["kind"] == "azure" else "direct"

    def entry(self, name, ep, reg):
        direct = self.route(ep) == "direct"
        anth = ep["kind"] == "anthropic"
        e = {"baseUrl": self.base_for(name, ep, reg, "anthropic" if anth else "openai"),
             "api": "anthropic-messages" if anth and direct else "openai-completions",
             "apiKey": ("$" + ep["key_env"]) if direct and ep.get("key_env") else proxy_key(self.app),
             "models": [dict({"id": m, "name": m}, **({"contextWindow": ep["context_window"]}
                                                     if ep.get("context_window") else {}))
                        for m in ep["models"]]}
        if direct and ep.get("headers"):
            e["headers"] = {k: env_ref(v, "pi") for k, v in ep["headers"].items()}
        return e

    def sync(self, reg, eps, gone):
        path = self.pdir() / "models.json"
        if Workbench(self.app).detected():
            if eps:
                self.ctx.say("note", path, "provider entries are written by 70-workbench (wb-state)")
            eps = {}
            gone = list(gone) + [n for n in reg["endpoints"]]
        want = {("providers", n): kf.REMOVE for n in gone}
        for n, ep in eps.items():
            want[("providers", n)] = self.entry(n, ep, reg)
        if eps or any(self.ctx.owned(path, k) is not kf.MISSING for k in want):
            kf.json_settings(self.ctx, path, want)
            protect(self.ctx, path)
        spath = self.pdir() / "settings.json"
        name = reg.get("default")
        sw = {("defaultProvider",): kf.REMOVE, ("defaultModel",): kf.REMOVE}
        if reg.get("default_explicit") and name in reg["endpoints"] and self.detected():
            sw = {("defaultProvider",): name,
                  ("defaultModel",): reg.get("default_model") or reg["endpoints"][name]["models"][0]}
        elif not any(self.ctx.owned(spath, k) is not kf.MISSING for k in sw):
            return
        kf.json_settings(self.ctx, spath, sw)

    def show(self, reg, name, ep):
        return json.dumps({"providers": {name: self.entry(name, ep, reg)}}, indent=2)


# --- Copilot CLI ------------------------------------------------------------------------------

class CopilotCli(Target):
    name, label = "copilot", "GitHub Copilot CLI (BYOK)"
    binaries = ["copilot"]
    protocols = "OpenAI chat or Responses, Azure, Anthropic (COPILOT_PROVIDER_* env vars)"
    mechanism = ("wrapper copilot-<name> (env vars, key via COPILOT_PROVIDER_API_KEY_COMMAND); "
                 "`default --also copilot`: exported by the shell snippet")

    def config_dirs(self):
        return [Path(os.environ.get("COPILOT_HOME") or self.home / ".copilot")]

    def route(self, ep):
        return "direct"

    def env_for(self, name, ep, reg) -> dict:
        kind = {"ollama": "openai"}.get(ep["kind"], ep["kind"])
        base = {"anthropic": anth_root(ep), "azure": ep["base_url"].rstrip("/")}.get(kind, openai_base(ep))
        env = {"COPILOT_PROVIDER_TYPE": kind, "COPILOT_PROVIDER_BASE_URL": base,
               "COPILOT_MODEL": ep["models"][0]}
        if ep.get("key_env"):
            env["COPILOT_PROVIDER_API_KEY_COMMAND"] = f"{key_helper_path(self.app)} {ep['key_env']}"
        if kind == "azure":
            env["COPILOT_PROVIDER_AZURE_API_VERSION"] = ep.get("api_version") or ""
            env["COPILOT_PROVIDER_WIRE_MODEL"] = ep["models"][0]
        if ep.get("headers"):
            env["COPILOT_PROVIDER_HEADERS"] = headers_block(ep)
        return env

    def sync(self, reg, eps, gone):
        for name in gone:
            remove_wrapper(self.app, "copilot", name)
        for name, ep in eps.items():
            lines = [f"export {k}={sh_dq(v)}" for k, v in self.env_for(name, ep, reg).items()]
            write_wrapper(self.app, "copilot", name, lines, 'exec copilot "$@"', False)

    def show(self, reg, name, ep):
        return "\n".join(f"export {k}={sh_dq(v)}" for k, v in self.env_for(name, ep, reg).items())


