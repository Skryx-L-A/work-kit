class OpenCode(Target):
    name, label = "opencode", "opencode"
    binaries = ["opencode"]
    protocols = "OpenAI chat, OpenAI Responses, Anthropic, Azure (AI SDK packages)"
    mechanism = "opencode.json provider.<name> ({env:VAR} for the key); default: model"

    def cfg(self):
        return Path(os.environ.get("XDG_CONFIG_HOME") or self.home / ".config") / "opencode"

    def config_dirs(self):
        return [self.cfg()]

    def route(self, ep):
        return "proxy" if ep["kind"] == "azure" else "direct"

    def entry(self, name, ep, reg):
        direct = self.route(ep) == "direct"
        anth = ep["kind"] == "anthropic"
        opts = {"baseURL": self.base_for(name, ep, reg, "anthropic-v1" if anth else "openai")}
        if direct and ep.get("key_env"):
            opts["apiKey"] = "{env:%s}" % ep["key_env"]
        elif not direct:
            opts["apiKey"] = proxy_key(self.app)
        if direct and ep.get("headers"):
            opts["headers"] = {k: env_ref(v, "opencode") for k, v in ep["headers"].items()}
        return {"npm": "@ai-sdk/anthropic" if anth and direct else "@ai-sdk/openai-compatible",
                "name": f"{name} (kit-models)", "options": opts,
                "models": {m: dict({"name": m}, **({"limit": {"context": ep["context_window"],
                                                                "output": min(16384, ep["context_window"] // 4)}}
                                                     if ep.get("context_window") else {}))
                           for m in ep["models"]}}

    def sync(self, reg, eps, gone):
        path = self.cfg() / "opencode.json"
        if (self.cfg() / "opencode.jsonc").exists() and not path.exists():
            if eps:
                self.ctx.say("note", self.cfg() / "opencode.jsonc",
                             "kit-models writes opencode.json; add the provider by hand: kit-models show <name> --target opencode")
            return
        want = {("provider", n): kf.REMOVE for n in gone}
        for n, ep in eps.items():
            want[("provider", n)] = self.entry(n, ep, reg)
        name = reg.get("default")
        if reg.get("default_explicit") and name in eps:
            want[("model",)] = f"{name}/{reg.get('default_model') or eps[name]['models'][0]}"
        elif self.ctx.owned(path, ("model",)) is not kf.MISSING:
            want[("model",)] = kf.REMOVE
        if not eps and not any(self.ctx.owned(path, k) is not kf.MISSING for k in want):
            return
        kf.json_settings(self.ctx, path, want)
        protect(self.ctx, path)

    def show(self, reg, name, ep):
        return json.dumps({"provider": {name: self.entry(name, ep, reg)},
                           "model": f"{name}/{ep['models'][0]}"}, indent=2)


