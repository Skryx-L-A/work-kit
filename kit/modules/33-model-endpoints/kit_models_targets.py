"""Targets of kit-models: every harness and kit tool that can use a registered endpoint.

Each target rewrites its own entries from the registry on every sync (idempotent) and removes
entries of endpoints that are gone. Ownership, merge and backup rules: kit_models_files.
Protocol facts and sources: docs/model-endpoints.md of the kit repository.

Route per target and endpoint: "direct" (the harness talks to the endpoint and reads the key
from the environment variable) or "proxy" (the harness talks to the local translating proxy,
which adds key and headers; used when the harness lacks the protocol, cannot reference an
environment variable for the key, or cannot send the custom headers).
"""
