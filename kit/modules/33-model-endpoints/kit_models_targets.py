BY_NAME = {t.name: t for t in TARGETS}


# --- driver -----------------------------------------------------------------------------------

def applies(t: Target, ep: dict) -> bool:
    sel = ep.get("targets")
    if sel == ["all"]:
        return True
    if sel:
        return t.name in sel
    return t.detected()


def sync_all(app, reg: dict, only=None) -> None:
    """Rewrite every target from the registry; drop entries of endpoints that are gone."""
    ctx = app.ctx
    write_key_helper(app)
    known = ctx.state.setdefault("targets", {})
    for cls in TARGETS:
        if only and cls.name not in only:
            continue
        t = cls(app)
        eps = {n: ep for n, ep in reg["endpoints"].items() if applies(t, ep)}
        before = set(known.get(t.name) or [])
        gone = sorted(before - set(eps))
        if not eps and not gone and t.name not in ("claude", "gemini", "meeting", "pi", "codex",
                                                   "opencode", "aider"):
            continue
        try:
            t.sync(reg, eps, gone)
        except OSError as e:
            ctx.say("skip", t.label, f"{e.__class__.__name__}: {e}")
            continue
        if sorted(eps) != sorted(before):
            known[t.name] = sorted(eps)
            ctx.state_dirty = True
    extra = {}
    for n in ("llm-usage",):
        extra.update(BY_NAME[n](app).env(reg))
    app.extra_env = extra


def remove_all(app, reg: dict, name: str) -> None:
    """Called before the endpoint leaves the registry; sync_all afterwards removes it."""


def uses_proxy(app, reg: dict) -> bool:
    for n, ep in reg["endpoints"].items():
        for cls in TARGETS:
            t = cls(app)
            if cls.name in ("cursor", "doc-qa", "llm-usage"):
                continue
            if applies(t, ep) and t.route(ep) == "proxy" and cls.name not in ("gemini",):
                return True
        if "gemini" in (reg.get("takeover") or []) or "meeting" in (reg.get("takeover") or []):
            return True
    return False


def matrix(app) -> str:
    rows = ["target            detected  support  native protocols / mechanism"]
    for cls in TARGETS:
        t = cls(app)
        rows.append(f"{t.name:17} {'yes' if t.detected() else 'no':9} {t.support:8} {t.protocols}")
        rows.append(f"{'':37}{t.mechanism}")
    return "\n".join(rows)


def show(app, reg: dict, name: str, target=None) -> str:
    ep = reg["endpoints"][name]
    out = []
    for cls in TARGETS:
        if target and cls.name != target:
            continue
        t = cls(app)
        text = t.show(reg, name, ep)
        if text:
            route = t.route(ep)
            out.append(f"== {t.label} ({t.name}; route: {route})\n{text}")
    if target and not out:
        raise SystemExit(f"kit-models: unknown target '{target}'")
    return "\n\n".join(out)
