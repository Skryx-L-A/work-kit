def json_list_sync(ctx, path: Path, list_key, id_field: str, entries: dict, gone_ids: list):
    """Upsert entries {id: obj} into a JSON list (the file itself, or data[list_key]) and drop
    gone ids, only where the current object is still the one kit-models wrote last time."""
    exists = path.exists()
    if not exists and not entries:
        return
    text = kf.read(path) if exists else ""
    try:
        data = json.loads(text) if text.strip() else ([] if list_key is None else {})
    except ValueError:
        try:
            json.loads(kf.strip_jsonc(text))
            ctx.say("skip", path, "has comments; add the entries by hand (kit-models show <name>)")
        except ValueError:
            ctx.say("skip", path, "not valid JSON; left untouched")
        return
    lst = data if list_key is None else data.setdefault(list_key, [])
    if not isinstance(lst, list):
        ctx.say("skip", path, "unexpected shape; left untouched")
        return
    before = json.dumps(data, sort_keys=True)
    index = {x.get(id_field): i for i, x in enumerate(lst) if isinstance(x, dict)}
    for eid in list(gone_ids) + [k for k in entries]:
        pass
    for eid in gone_ids:
        if eid in entries:
            continue
        owned = ctx.owned(path, ("#list", eid))
        if eid in index and owned is not kf.MISSING and lst[index[eid]] == owned:
            lst[index[eid]] = None
        ctx.disown(path, ("#list", eid))
    for eid, obj in entries.items():
        owned = ctx.owned(path, ("#list", eid))
        if eid in index:
            cur = lst[index[eid]]
            if cur == obj:
                ctx.own(path, ("#list", eid), obj)
            elif owned is not kf.MISSING and cur == owned:
                lst[index[eid]] = obj
                ctx.own(path, ("#list", eid), obj)
            else:
                ctx.disown(path, ("#list", eid))
                ctx.say("keep", path, f"'{eid}' was changed by you; kit-models entry not applied")
        else:
            lst.append(obj)
            ctx.own(path, ("#list", eid), obj)
    lst[:] = [x for x in lst if x is not None]
    if json.dumps(data, sort_keys=True) == before:
        if exists:
            ctx.say("unchanged", path)
        return
    if exists:
        ctx.backup(path)
    ctx.write_text(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    ctx.say("update" if exists else "create", path)


