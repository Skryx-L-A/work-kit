# --- local proxy token ------------------------------------------------------------------------

def proxy_key(app, shell: bool = False) -> str:
    """What a harness sends to the local proxy: the per-install token (app.proxy_token()), not an
    endpoint key. In a shell wrapper (mode 0755) a variable reference instead of the value; the
    wrapper sources the snippet that exports it from the 0600 token file."""
    return "${%s}" % PROXY_KEY_VAR if shell else app.proxy_token()


def protect(ctx, path) -> None:
    """A file that holds the token literally must not be readable by other local users."""
    try:
        if not ctx.dry_run and Path(path).is_file() and Path(path).stat().st_mode & 0o077:
            os.chmod(path, 0o600)
    except OSError:
        pass


# --- route helpers ----------------------------------------------------------------------------

def dyn_headers(ep) -> bool:
    return any("${" in v for v in (ep.get("headers") or {}).values())


def is_loopback(url: str) -> bool:
    return (urllib.parse.urlsplit(url).hostname or "") in ("127.0.0.1", "localhost", "::1")


def openai_base(ep) -> str:
    """OpenAI-compatible base URL ending in /v1 (or whatever the endpoint uses)."""
    base = ep["base_url"].rstrip("/")
    if ep["kind"] == "ollama" and not base.endswith("/v1"):
        base += "/v1"
    return base


def anth_root(ep) -> str:
    base = ep["base_url"].rstrip("/")
    return base[:-3] if base.endswith("/v1") else base


def anth_v1(ep) -> str:
    return anth_root(ep) + "/v1"


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "model"


def env_ref(value: str, style: str) -> str:
    """Rewrite ${VAR} references for a config format."""
    fmt = {"opencode": "{env:\\1}", "pi": "${\\1}", "shell": "${\\1}"}[style]
    return re.sub(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}", fmt, value)


def sh_dq(value: str) -> str:
    """Double-quoted shell word that keeps ${VAR} references and escapes everything else."""
    parts = re.split(r"(\$\{[A-Za-z_][A-Za-z0-9_]*\})", value)
    out = []
    for p in parts:
        if re.fullmatch(r"\$\{[A-Za-z_][A-Za-z0-9_]*\}", p):
            out.append(p)
        else:
            out.append(re.sub(r'([\\"$`])', r"\\\1", p))
    return '"' + "".join(out) + '"'


def which(binary: str, home: Path):
    dirs = os.environ.get("PATH", "").split(os.pathsep) + [str(home / ".local/bin")]
    for d in dirs:
        p = Path(d) / binary
        if p.is_file() and os.access(p, os.X_OK):
            return p
    return None


# --- base class -------------------------------------------------------------------------------

class Target:
    name = ""
    label = ""
    binaries: list = []
    protocols = ""      # what it speaks natively (for the matrix)
    mechanism = ""      # how kit-models configures it
    support = "full"    # full | partial | manual

    def __init__(self, app):
        self.app = app
        self.ctx = app.ctx
        self.home = app.home

    def config_dirs(self) -> list:
        return []

    def detected(self) -> bool:
        return any(which(b, self.home) for b in self.binaries) or any(
            Path(d).exists() for d in self.config_dirs())

    def route(self, ep) -> str:
        return "proxy"

    def base_for(self, name, ep, reg, protocol="openai") -> str:
        """Base URL the target uses for this endpoint (proxy or direct)."""
        if self.route(ep) == "proxy":
            b = self.app.proxy_base(name, reg)
            return b + "/v1" if protocol in ("openai", "anthropic-v1") else b
        if protocol == "anthropic":
            return anth_root(ep)
        if protocol == "anthropic-v1":
            return anth_v1(ep)
        return openai_base(ep)

    def sync(self, reg, eps: dict, gone: list) -> None:
        """Write entries for eps {name: ep}; remove entries of endpoints in gone."""

    def show(self, reg, name, ep) -> str:
        return ""


# --- wrappers (claude-<name>, codex-<name>, ...) ----------------------------------------------

def key_helper_path(app) -> Path:
    return app.data / "key-helper"


def write_key_helper(app) -> None:
    kit = app.ctx.bin_dir / "kit-models"
    body = f"""#!/bin/sh
{WRAP_MARK}
# key-helper VAR: print the value of the variable VAR (environment, then
# {app.secrets_file}, then the desktop secret store). key-helper --proxy: make sure the local
# proxy runs and print the local proxy token (from the 0600 token file). Used by harness settings (apiKeyHelper,
# COPILOT_PROVIDER_API_KEY_COMMAND) so that no key is written into a harness config.
if [ "$1" = "--proxy" ]; then
  pid=$(cat "{app.data}/proxy.pid" 2>/dev/null)
  if [ -z "$pid" ] || ! kill -0 "$pid" 2>/dev/null; then "{kit}" proxy start >/dev/null 2>&1; fi
  cat "{app.token_file}"
  exit 0
fi
v=$(printenv "$1")
if [ -z "$v" ] && [ -r "{app.secrets_file}" ]; then v=$(. "{app.secrets_file}" >/dev/null 2>&1; printenv "$1"); fi
if [ -z "$v" ] && command -v secret-tool >/dev/null 2>&1; then
  v=$(secret-tool lookup service work-kit key "$1" 2>/dev/null)
fi
[ -n "$v" ] || {{ echo "key-helper: $1 is not set (kit-models add --new-key)" >&2; exit 1; }}
printf '%s' "$v"
"""
    kf.write_managed_file(app.ctx, key_helper_path(app), body, WRAP_MARK, 0o755)


def wrapper_path(app, harness: str, name: str) -> Path:
    return app.ctx.bin_dir / f"{harness}-{name}"


def write_wrapper(app, harness: str, name: str, lines: list, exec_line: str, proxy: bool) -> None:
    kit = app.ctx.bin_dir / "kit-models"
    body = ["#!/usr/bin/env bash", WRAP_MARK,
            f"# Runs {harness} against the endpoint '{name}' registered with kit-models.",
            f'[ -r "{app.env_file}" ] && . "{app.env_file}"']
    if proxy:
        body.append(f'"{kit}" proxy start >/dev/null || exit 1')
    body += lines + [exec_line]
    kf.write_managed_file(app.ctx, wrapper_path(app, harness, name), "\n".join(body) + "\n",
                          WRAP_MARK, 0o755)


def remove_wrapper(app, harness: str, name: str) -> None:
    kf.remove_managed_file(app.ctx, wrapper_path(app, harness, name), WRAP_MARK)


def headers_block(ep) -> str:
    return "\n".join(f"{k}: {v}" for k, v in (ep.get("headers") or {}).items())


# --- Claude Code ------------------------------------------------------------------------------

class Claude(Target):
    name, label = "claude", "Claude Code"
    binaries = ["claude"]
    protocols = "Anthropic Messages only"
    mechanism = ("wrapper claude-<name> (env + apiKeyHelper via --settings); `default --also claude`: "
                 "~/.claude/settings.json env + apiKeyHelper")

    def cdir(self):
        return Path(os.environ.get("CLAUDE_CONFIG_DIR") or self.home / ".claude")

    def config_dirs(self):
        return [self.cdir()]

    def route(self, ep):
        return "direct" if ep["kind"] == "anthropic" else "proxy"

    def env_for(self, name, ep, reg, model, resolved_headers: bool):
        env = {"ANTHROPIC_BASE_URL": self.base_for(name, ep, reg, "anthropic"),
               "ANTHROPIC_MODEL": model, "ANTHROPIC_DEFAULT_OPUS_MODEL": model,
               "ANTHROPIC_DEFAULT_SONNET_MODEL": model, "ANTHROPIC_DEFAULT_HAIKU_MODEL": model,
               "ANTHROPIC_DEFAULT_FABLE_MODEL": model, "CLAUDE_CODE_SUBAGENT_MODEL": model}
        if ep.get("context_window"):
            env["CLAUDE_CODE_MAX_CONTEXT_TOKENS"] = str(ep["context_window"])
        if self.route(ep) == "direct" and ep.get("headers") and (resolved_headers or not dyn_headers(ep)):
            env["ANTHROPIC_CUSTOM_HEADERS"] = headers_block(ep)
        return env

    def helper(self, ep):
        if self.route(ep) == "proxy" or not ep.get("key_env"):
            return f"{key_helper_path(self.app)} --proxy" if self.route(ep) == "proxy" else None
        return f"{key_helper_path(self.app)} {ep['key_env']}"

    def sync(self, reg, eps, gone):
        for name in gone:
            remove_wrapper(self.app, "claude", name)
        for name, ep in eps.items():
            model = ep["models"][0]
            env = self.env_for(name, ep, reg, model, True)
            lines = [f"export {k}={sh_dq(v)}" for k, v in env.items()]
            helper = self.helper(ep)
            settings = json.dumps({"apiKeyHelper": helper}) if helper else "{}"
            write_wrapper(self.app, "claude", name, lines,
                          f"exec claude --settings {sh_quote(settings)} \"$@\"",
                          self.route(ep) == "proxy")
        self.takeover(reg, eps)

    def takeover(self, reg, eps):
        path = self.cdir() / "settings.json"
        keys = ["ANTHROPIC_BASE_URL", "ANTHROPIC_MODEL", "ANTHROPIC_DEFAULT_OPUS_MODEL",
                "ANTHROPIC_DEFAULT_SONNET_MODEL", "ANTHROPIC_DEFAULT_HAIKU_MODEL",
                "ANTHROPIC_DEFAULT_FABLE_MODEL", "CLAUDE_CODE_SUBAGENT_MODEL",
                "ANTHROPIC_CUSTOM_HEADERS", "CLAUDE_CODE_MAX_CONTEXT_TOKENS"]
        name = reg.get("default")
        want = {("env", k): kf.REMOVE for k in keys}
        want[("apiKeyHelper",)] = kf.REMOVE
        if "claude" in (reg.get("takeover") or []) and name in eps:
            ep = eps[name]
            if ep["kind"] == "anthropic" and dyn_headers(ep):
                ep = dict(ep, kind="openai")  # secret headers: through the proxy
            env = self.env_for(name, ep, reg, reg.get("default_model") or ep["models"][0], False)
            for k, v in env.items():
                want[("env", k)] = v
            h = self.helper(ep)
            if h:
                want[("apiKeyHelper",)] = h
        elif not any(self.ctx.owned(path, k) is not kf.MISSING for k in want):
            return
        kf.json_settings(self.ctx, path, want)

    def show(self, reg, name, ep):
        env = self.env_for(name, ep, reg, ep["models"][0], False)
        lines = [f"export {k}={sh_dq(v)}" for k, v in env.items()]
        h = self.helper(ep)
        return ("\n".join(lines) + (f"\n# ~/.claude/settings.json: \"apiKeyHelper\": \"{h}\"" if h else "")
                + f"\n# or simply run: claude-{name}")


def sh_quote(v: str) -> str:
    return "'" + v.replace("'", "'\"'\"'") + "'"


# --- Codex ------------------------------------------------------------------------------------

class Codex(Target):
    name, label = "codex", "Codex CLI"
    binaries = ["codex"]
    protocols = "OpenAI Responses only (wire_api = \"chat\" was removed)"
    mechanism = ("~/.codex/config.toml [model_providers.<name>] (region); default: model_provider + model "
                 "(region at the top); wrapper codex-<name>")
    TOP = ("# work-kit:begin model-default - managed by kit-models", "# work-kit:end model-default")
    TABLES = ("# work-kit:begin model-providers - managed by kit-models",
              "# work-kit:end model-providers")

    def chome(self):
        return Path(os.environ.get("CODEX_HOME") or self.home / ".codex")

    def config_dirs(self):
        return [self.chome()]

    def route(self, ep):
        return "direct" if ep["kind"] == "openai" and ep.get("responses") else "proxy"

    def table(self, name, ep, reg) -> list:
        lines = [f"[model_providers.{kf.toml_key(name)}]",
                 f"name = {kf.toml_str(name + ' (kit-models)')}",
                 f"base_url = {kf.toml_str(self.base_for(name, ep, reg))}",
                 'wire_api = "responses"']
        if self.route(ep) == "direct":
            if ep.get("key_env"):
                lines.append(f"env_key = {kf.toml_str(ep['key_env'])}")
            static = {k: v for k, v in (ep.get("headers") or {}).items() if "${" not in v}
            envh = {k: re.fullmatch(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}", v).group(1)
                    for k, v in (ep.get("headers") or {}).items()
                    if re.fullmatch(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}", v)}
            if static:
                lines.append(f"http_headers = {kf.toml_str(static)}")
            if envh:
                lines.append(f"env_http_headers = {kf.toml_str(envh)}")
        else:  # the local proxy needs its token, exported by the shell snippet
            lines.append(f"env_key = {kf.toml_str(PROXY_KEY_VAR)}")
        return lines

    def sync(self, reg, eps, gone):
        path = self.chome() / "config.toml"
        for name in gone:
            remove_wrapper(self.app, "codex", name)
        body = []
        for name, ep in sorted(eps.items()):
            body += self.table(name, ep, reg) + [""]
            write_wrapper(self.app, "codex", name, [],
                          f"exec codex -c model_provider={sh_quote(name)} -c model={sh_quote(json.dumps(ep['models'][0]))} \"$@\"",
                          self.route(ep) == "proxy")
        if not eps and not path.exists():
            return
        kf.set_region(self.ctx, path, *self.TABLES, "\n".join(body), "end", check_toml=True)
        top = ""
        name = reg.get("default")
        if reg.get("default_explicit") and name in eps:
            old = kf.read(path) if path.exists() else ""
            outside = kf.region_re(*self.TOP).sub("", old)
            head = re.split(r"(?m)^\s*\[", outside, maxsplit=1)[0]
            if re.search(r"(?m)^\s*(model|model_provider)\s*=", head):
                self.ctx.say("keep", path, "model / model_provider are set by you; kit-models default not applied")
            else:
                model = reg.get("default_model") or eps[name]["models"][0]
                top = f"model_provider = {kf.toml_str(name)}\nmodel = {kf.toml_str(model)}"
        kf.set_region(self.ctx, path, *self.TOP, top, "start", check_toml=True)

    def show(self, reg, name, ep):
        return "\n".join(self.table(name, ep, reg)) + f"\n# run: codex-{name}  (or codex -c model_provider={name})"


